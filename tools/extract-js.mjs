/* Guarded binding. The original script bound straight to elements at the top level,
   which is safe in a single-page app where every view is in the DOM and fatal on a
   generated page that only carries its own markup. */
function on(sel, ev, fn, opts) {
  const el = typeof sel === 'string' ? $(sel) : sel;
  if (el) el.addEventListener(ev, fn, opts);
  return !!el;
}

/* Data loading. Nothing here runs before first paint — every page is server-rendered
   and these are fetched only when an interactive feature actually needs them. */
let BOOKS = [], ID2I = {}, EDGES = [], SLUGS = {};
