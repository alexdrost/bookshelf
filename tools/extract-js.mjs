/** Slice by 1-indexed inclusive start .. exclusive end, exactly as mapped. */
const cut = (a, b) => L.slice(a - 1, b - 1).join('\n');

const log = [];
function patch(src, find, replace, label) {
  const n = src.split(find).length - 1;
  if (n === 0) { console.error(`✗ patch "${label}" matched nothing`); process.exit(1); }
  log.push(`  ${label} (${n}×)`);
  return src.split(find).join(replace);
}

