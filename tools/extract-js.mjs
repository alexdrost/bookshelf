// tools/extract-js.mjs — SESSION 2 Step 1.
//
// Splits the SPA's single inline <script> into four modules. Function bodies are
// sliced VERBATIM by line range out of the original — this file never retypes them.
// Only two categories of change are applied, both logged:
//
//   BIND  a top-level `$("#x").addEventListener(...)` becomes `on("#x", ...)`, a
//         helper that no-ops when the element is absent. Needed because each page
//         now carries only its own markup, and the original bindings assume every
//         view exists in the DOM.
//   LINK  `onclick="openModal(BOOKS[i])"` becomes a real <a href="/book/{slug}">.
//         The modal is retired in SESSION 2 — the book page is its replacement.
//
// Deleted outright (SESSION 2 Step 1 + Step 8):
//   probeImg / lookupCover / applyCover / resolveCoverContainer / coverObserver /
//   observeCovers / tfetch / gbPick / olISBN / coverCache   — the speculative cover
//     probe and its Open Library + Google Books fallback chain. The build knows
//     which covers exist.
//   lookupFace / faceCache / faceObserver / hydrateFace / observeFaces / avatarHTML /
//   SIL / normAuthorMap / renderAuthors / renderAuthorBatch / openAuthor /
//   closeAuthor / booksByAuthor            — the Authors view, removed entirely.
//   showView / readState / writeState / activeView / ensureView / gotoTheme /
//   gotoYear / gotoYearReview / dataError / bootstrap   — SPA hash routing, replaced
//     by real URLs.

